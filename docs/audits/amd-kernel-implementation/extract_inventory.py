def text(path):
    return Path(path).read_text(encoding="utf-8-sig")

def reference(file, symbol=None, line=None, root=SOURCE):
    path = root / file
    content = text(path)
    found = []
    if path.suffix == ".py" and symbol is not None:
        tree = ast.parse(content)
        def scan(node, prefix=""):
            for child in ast.iter_child_nodes(node):
                if isinstance(child, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                    name = prefix + child.name
                    if name == symbol:
                        found.append(child)
                    scan(child, name + ".")
                else:
                    scan(child, prefix)
        scan(tree)
        if len(found) != 1:
            raise ValueError(f"Expected one definition: {file}::{symbol}, found {len(found)}")
        line = found[0].lineno
        end = found[0].end_lineno
    else:
        if line is None:
            hits = [i+1 for i, s in enumerate(content.splitlines()) if symbol in s]
            if not hits:
                raise ValueError(f"Missing anchor {file}::{symbol}")
            line = hits[0]
        end = line
    return dict(file=file, path=path.as_posix(), symbol=symbol, line=line, end_line=end,
                sha256=digest(path), link=f"{path.as_posix()}:{line}")

