def row(id, stage, file, symbol, callable, shape, math, rw, producer, consumer,
        amd_key, difference, opportunity="already", evidence="static", gate=None,
        binding=None, predicate=None, line=None, sites=None, kind="triton_kernel"):
    r = dict(id=id, stage=stage, kind=kind, local=reference(file, symbol, line),
             actual_callable=callable, shape_dtype_fullK=shape, arithmetic=math,
             reads_writes_layout_temporaries=rw, producer=producer, consumer=consumer,
             amd=[A[amd_key]] if amd_key else [], comparison=difference,
             improvement=opportunity, evidence_class=evidence, evidence_gate=gate,
             binding_symbol=binding or (symbol if kind == "triton_kernel" else None),
             binding_predicate=predicate or {}, sites=sites or [],
             dynamic_dispatch_trace=False, physical_memory_traffic_measured=False)
    ROWS.append(r)
    return r

