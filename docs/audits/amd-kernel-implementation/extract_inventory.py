def gain(op):
    if op in {'N1','N2','N3','N4','N5','N6'}:
        budgets={'N1':(1,[0,.8]),'N2':(1,[0,1.5]),'N3':(1,[0,2.5]),'N4':(2,[0,.6]),'N5':(2,[0,.6]),'N6':(3,[0,.25])}
        pri,budget=budgets[op]
        return dict(plan=op,priority=pri,whole_module_budget_ms=budget,
            qualification='unmeasured estimate inherited from original PLAN; shared by all rows of module, not additive per row',
            minimum_Luna_experiment='one isolated whole-module swap on accepted baseline; same13 full frames/fullK/motion/history/controls; balanced A/B/B/A repeat; no GPU by this extractor')
    return dict(plan=op,priority=3 if op.startswith('gap-') else 0,whole_module_budget_ms=None,
        qualification='new gap unbudgeted; no measured gain assigned' if op.startswith('gap-') else 'already implemented or no current new gain',
        minimum_Luna_experiment='new gap: independent whole-frame isolated swap before assigning budget' if op.startswith('gap-') else None)

